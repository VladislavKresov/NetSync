"""Standard Markdown links for the docs: turns Obsidian wiki links into relative links GitHub can follow.

    python tools/mdlinks.py            converts every note under docs/ in place
    python tools/mdlinks.py --check    lists notes that still contain wiki links (exit code 1 if any)

    [[Note]]              -> [Note](relative/path/Note.md)
    [[Note#Heading]]      -> [Heading](relative/path/Note.md#heading)
    [[Note|text]]         -> [text](relative/path/Note.md)   (also the \\| form used inside tables)
    > [!info] / [!tip]    -> > [!NOTE] / [!TIP]               (the alert types GitHub renders)

Code blocks and inline code are left alone. generate-vault.py writes its notes through convert(),
so generated and hand-written notes follow the same rules.
"""
import os
import re
import sys
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")

WIKI_LINK = re.compile(r"\[\[([^\]|#\\]+?)(?:#([^\]|\\]+?))?(?:\\?\|([^\]]+?))?\]\]")
CALLOUTS = {"info": "NOTE", "note": "NOTE", "tip": "TIP", "hint": "TIP", "important": "IMPORTANT",
            "warning": "WARNING", "caution": "CAUTION", "danger": "CAUTION"}
INLINE_CODE = re.compile(r"(`+)(.+?)\1")
# The index note is docs/README.md (GitHub shows it for the folder); it used to be called Home.
ALIASES = {"Home": "README"}


def build_index(paths):
    """Note name (file name without .md; other files by full name) -> absolute path."""
    index = {}
    for path in paths:
        name = os.path.basename(path)
        index[name[:-3] if name.endswith(".md") else name] = path
    return index


def scan(root=DOCS):
    found = []
    for folder, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith(".")]
        found += [os.path.join(folder, f) for f in files if f.endswith((".md", ".canvas"))]
    return found


def github_anchor(heading):
    """The anchor GitHub gives a heading: lower case, punctuation dropped, spaces to hyphens."""
    text = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return text.replace(" ", "-")


def link_target(from_path, target_path, heading):
    relative = os.path.relpath(target_path, os.path.dirname(from_path)).replace(os.sep, "/")
    url = urllib.parse.quote(relative, safe="/._-~")
    return url + ("#" + github_anchor(heading) if heading else "")


def convert_line(line, from_path, index, missing):
    def replace(match):
        name, heading, label = match.group(1).strip(), match.group(2), match.group(3)
        target = index.get(ALIASES.get(name, name))
        text = (label or (heading or name)).strip()
        if target is None:
            missing.add(name)
            return text
        return f"[{text}]({link_target(from_path, target, heading)})"

    # Only outside inline code spans.
    parts, last = [], 0
    for code in INLINE_CODE.finditer(line):
        parts.append(WIKI_LINK.sub(replace, line[last:code.start()]))
        parts.append(code.group(0))
        last = code.end()
    parts.append(WIKI_LINK.sub(replace, line[last:]))
    return "".join(parts)


def convert(text, from_path, index, missing=None):
    """Converts the wiki links and callouts of one note, given where it lives."""
    missing = set() if missing is None else missing
    out, fenced = [], False
    for line in text.split("\n"):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
            out.append(line)
            continue
        out.append(line if fenced else convert_line(line, from_path, index, missing))
    result = "\n".join(out)
    if not from_path.endswith(".canvas"):
        result = CALLOUT_LINE.sub(callout, result)
    return result


CALLOUT_LINE = re.compile(r"^([ \t]*>[ \t]*)\[!(\w+)\][+-]?[ \t]*([^\r\n]*)(\r?)$", re.MULTILINE)


def callout(match):
    """GitHub shows an alert only when its marker stands alone: an Obsidian title moves to the next line, in bold."""
    quote, kind, title, cr = match.group(1), match.group(2), match.group(3).strip(), match.group(4)
    marker = f"{quote}[!{CALLOUTS.get(kind.lower(), kind.upper())}]{cr}"
    if not title:
        return marker
    return f"{marker}\n{quote}**{title}**{cr}" if not title.startswith("Generated by") else f"{marker}\n{quote}{title}{cr}"


MARKDOWN_LINK = re.compile(r"\]\(([^)\s]+)\)")
HEADING = re.compile(r"^#{1,6}\s+(.+?)\s*#*\s*$", re.MULTILINE)


def anchors(path):
    with open(path, encoding="utf-8") as f:
        return {github_anchor(h) for h in HEADING.findall(f.read())}


def check(paths):
    """Wiki links left over, and relative links whose file or heading doesn't exist."""
    problems = []
    for path in paths:
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        where = os.path.relpath(path, ROOT)
        if WIKI_LINK.search(text):
            problems.append(f"{where}: wiki link left")
        prose = re.sub(r"```.*?```", "", text, flags=re.DOTALL)
        for target in MARKDOWN_LINK.findall(prose):
            if re.match(r"^[a-z]+:", target):
                continue  # http(s), mailto
            file_part, _, anchor = target.partition("#")
            resolved = path if not file_part else os.path.normpath(
                os.path.join(os.path.dirname(path), urllib.parse.unquote(file_part)))
            if not os.path.exists(resolved):
                problems.append(f"{where}: broken link {target}")
            elif anchor and resolved.endswith(".md") and anchor not in anchors(resolved):
                problems.append(f"{where}: no heading #{anchor} in {os.path.relpath(resolved, ROOT)}")
    return problems


def main():
    notes = [p for p in scan() if p.endswith(".md")]
    if "--check" in sys.argv:
        problems = check(notes + [os.path.join(ROOT, name) for name in ("README.md", "CHANGELOG.md", "SECURITY.md")])
        for problem in problems:
            print(problem)
        sys.exit(1 if problems else 0)
    index = build_index(scan())
    missing = set()
    for path in notes:
        with open(path, encoding="utf-8") as f:
            text = f.read()
        converted = convert(text, path, index, missing)
        if converted != text:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(converted)
    if missing:
        print("links to notes that don't exist (left as plain text): " + ", ".join(sorted(missing)))


if __name__ == "__main__":
    main()
