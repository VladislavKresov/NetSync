KIND_RE = re.compile(
    r"^(?P<mods>(?:(?:public|internal|private|protected|static|sealed|abstract|partial|readonly|ref|unsafe|new)\s+)*)"
    r"(?P<kind>class|struct|interface|enum|record\s+struct|record|delegate\s+[\w<>\[\],.?\s]+?)\s+"
    r"(?P<name>[A-Z]\w*)(?P<generic><[^>{]*>)?(?P<rest>.*)$")


def strip_code(text):
    """Removes comments, string and char literals (keeps line structure)."""
    out = []
    i, n = 0, len(text)
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            while i < n and text[i] != "\n":
                i += 1
        elif c == "/" and nxt == "*":
            end = text.find("*/", i + 2)
            end = n if end < 0 else end + 2
            out.append("\n" * text.count("\n", i, end))
            i = end
        elif c == "@" and nxt == '"' or (c == "$" and nxt == "@") or (c == "@" and nxt == "$"):
            j = text.find('"', i)
            j += 1
            while j < n:
                if text[j] == '"' and j + 1 < n and text[j + 1] == '"':
                    j += 2
                elif text[j] == '"':
                    j += 1
                    break
                else:
                    j += 1
            out.append('""' + "\n" * text.count("\n", i, j))
            i = j
        elif c == '"' or (c == "$" and nxt == '"'):
            j = i + (2 if c == "$" else 1)
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            out.append('""')
            i = j + 1
        elif c == "'":
            j = i + 1
            while j < n and text[j] != "'" and j - i < 12:
                j += 2 if text[j] == "\\" else 1
            out.append("' '")
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def xml_summary(lines, index):
    """The /// <summary> right above line `index` (plain text, crefs kept as names)."""
    doc = []
    j = index - 1
    while j >= 0 and (lines[j].strip().startswith("///") or lines[j].strip().startswith("[")):
        if lines[j].strip().startswith("///"):
            doc.insert(0, lines[j].strip()[3:].strip())
        j -= 1
    text = " ".join(doc)
    m = re.search(r"<summary>(.*?)</summary>", text, re.S)
    if not m:
        return ""
    s = m.group(1)
    s = re.sub(r'<see(?:also)?\s+(?:cref|langword|href)="(?:[A-Z]:)?([^"]+)"\s*/>', lambda mm: "`" + mm.group(1).split(".")[-1].split("(")[0] + "`", s)
    s = re.sub(r'<paramref name="([^"]+)"\s*/>', r"`\1`", s)
    s = re.sub(r"</?c>", "`", s)
    s = re.sub(r"<code>.*?</code>", "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", "", s)
    s = s.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")
    return re.sub(r"\s+", " ", s).strip()


class Module:
    def __init__(self, name, folder):
        self.name = name
        self.folder = folder
        self.files = []
        self.namespace = ""
        self.types = []          # dicts: name, kind, mods, depth, summary, bases
        self.members = defaultdict(list)  # type name -> member signatures
        self.code = ""           # stripped code of all parts
        self.deps = set()
        self.users = set()
        self.via = defaultdict(set)  # dependency -> the type names that make it

    @property
    def main(self):
        for t in self.types:
            if t["name"] == self.name and t["depth"] == 0:
                return t
        top = [t for t in self.types if t["depth"] == 0]
        return top[0] if top else (self.types[0] if self.types else None)


def folder_of(path):
    rel = os.path.relpath(os.path.dirname(path), SRC).replace("\\", "/")
    return "(root)" if rel == "." else rel


def scan():
    modules = {}
    for dirpath, dirnames, filenames in os.walk(SRC):
        dirnames[:] = [d for d in dirnames if d not in ("bin", "obj")]
        for filename in sorted(filenames):
            if not filename.endswith(".cs"):
                continue
            path = os.path.join(dirpath, filename)
            stem = filename[:-3].split(".")[0]
            module = modules.setdefault(stem, Module(stem, folder_of(path)))
            module.files.append(os.path.relpath(path, ROOT).replace("\\", "/"))
            raw = open(path, encoding="utf-8-sig").read()
            raw_lines = raw.split("\n")
            code = strip_code(raw)
            module.code += code + "\n"
            ns = re.search(r"^namespace\s+([\w.]+)", code, re.M)
            if ns:
                module.namespace = ns.group(1)
            depth = 0           # brace depth
            type_stack = []     # (name, depth at which its body opens)
            pending_type = None
            ns_depth = 1 if ns and not re.search(r"^namespace\s+[\w.]+\s*;", code, re.M) else 0
            for line_no, line in enumerate(code.split("\n")):
                stripped = line.strip()
                m = KIND_RE.match(stripped)
                if m and not stripped.startswith(("return", "new ")) and "=" not in stripped.split("(")[0]:
                    kind = re.sub(r"\s+", " ", m.group("kind"))
                    if kind.startswith("delegate"):
                        kind = "delegate"
                    rest = m.group("rest")
                    bases = []
                    bm = re.match(r"\s*(?:\([^)]*\))?\s*:\s*([^{]+?)(?:\bwhere\b|\{|$)", rest)
                    if bm and kind != "enum":
                        bases = [re.sub(r"<.*", "", b).strip() for b in re.split(r",(?![^<]*>)", bm.group(1)) if b.strip()]
                    t = {"name": m.group("name"), "kind": kind, "mods": m.group("mods").split(),
                         "depth": len(type_stack), "summary": xml_summary(raw_lines, line_no), "bases": bases,
                         "generic": m.group("generic") or ""}
                    if not any(x["name"] == t["name"] and x["depth"] == t["depth"] for x in module.types):
                        module.types.append(t)
                    if kind not in ("delegate",) and not stripped.endswith(";"):
                        pending_type = t["name"]
                elif type_stack and depth == type_stack[-1][1] and re.match(r"(public|internal|protected)\s", stripped):
                    sig = re.split(r"\s*(?:\{|=>|;)", stripped)[0].strip()
                    if sig and not KIND_RE.match(stripped):
                        module.members[type_stack[-1][0]].append(sig)
                for ch in line:
                    if ch == "{":
                        depth += 1
                        if pending_type:
                            type_stack.append((pending_type, depth))
                            pending_type = None
                    elif ch == "}":
                        if type_stack and depth == type_stack[-1][1]:
                            type_stack.pop()
                        depth -= 1
    return modules


def resolve(modules):
    owner = {}
    ambiguous = set()
    for module in modules.values():
        for t in module.types:
            if t["depth"] != 0:
                continue
            if t["name"] in owner and owner[t["name"]] is not module:
                ambiguous.add(t["name"])
            owner[t["name"]] = module
    for name in ambiguous:
        owner.pop(name, None)
    for module in modules.values():
        for token in set(re.findall(r"\b[A-Z]\w*\b", module.code)):
            target = owner.get(token)
            if target is not None and target is not module:
                module.deps.add(target.name)
                module.via[target.name].add(token)
                target.users.add(module.name)
    return owner


def mid(name):
    return "m_" + re.sub(r"\W", "_", name)


def fid(folder):
    return "f_" + re.sub(r"\W", "_", folder)


def folder_note(folder):
    return "Module map " + ("root" if folder == "(root)" else folder.replace("/", " "))


def kind_label(t):
    mods = [m for m in t["mods"] if m in ("public", "internal", "private", "protected", "static", "abstract", "sealed")]
    return " ".join(mods + [t["kind"]])


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def code_note(module, modules):
    main = module.main
    folder_tag = module.folder.replace("/", "-").replace("(root)", "root")
    lines = ["---",
             f"tags: [code, layer/{layer_of(module.folder)}, folder/{folder_tag}]",
             f"namespace: {module.namespace}",
             f"kind: {main['kind'] if main else 'file'}",
             f"visibility: {next((m for m in (main['mods'] if main else []) if m in ('public', 'internal')), 'internal')}",
             "files:"] + [f"  - {f}" for f in module.files] + [
             f"depends_on: {len(module.deps)}", f"used_by: {len(module.users)}", "---", "",
             f"# {module.name}", "", GENERATED, ""]
    if main and main["summary"]:
        lines += [main["summary"], ""]
    lines += [f"**Namespace** `{module.namespace}` · **Folder** [[{folder_note(module.folder)}|{module.folder}]] · "
              f"**Layer** {layer_of(module.folder)}", "",
              "**Source** " + " · ".join(f"`{f}`" for f in module.files), ""]
    lines += ["## Types", "", "| Type | Kind | Summary |", "|---|---|---|"]
    for t in module.types:
        indent = "↳ " * t["depth"]
        summary = t["summary"].replace("|", "\\|")
        if len(summary) > 220:
            summary = summary[:217].rsplit(" ", 1)[0] + "…"
        lines.append(f"| {indent}`{t['name']}{t['generic']}` | {kind_label(t)} | {summary} |")
    lines.append("")
    bases = [(t["name"], b) for t in module.types if t["depth"] == 0 for b in t["bases"]]
    if bases:
        lines += ["## Extends / implements", ""]
        for name, base in bases:
            target = next((m for m in modules.values() if any(x["name"] == base and x["depth"] == 0 for x in m.types)), None)
            where = f" ([[{target.name}]])" if target and target is not module else ""
            lines.append(f"- `{name}` → `{base}`{where}")
        lines.append("")
    public_members = [(t, module.members.get(t["name"], [])) for t in module.types
                      if module.members.get(t["name"]) and "private" not in t["mods"]]
    if public_members:
        lines += ["## Members", ""]
        for t, members in public_members:
            lines.append(f"**{t['name']}**")
            lines.append("")
            lines += [f"- `{m}`" for m in members[:60]]
            if len(members) > 60:
                lines.append(f"- … {len(members) - 60} more")
            lines.append("")
    for title, names in (("Depends on", module.deps), ("Used by", module.users)):
        lines += [f"## {title} ({len(names)})", ""]
        if not names:
            lines += ["—", ""]
            continue
        by_folder = defaultdict(list)
        for name in names:
            by_folder[modules[name].folder].append(name)
        for folder in sorted(by_folder, key=folder_order):
            lines.append(f"- **{folder}**: " + ", ".join(link_with_via(module, n, modules, title) for n in sorted(by_folder[folder])))
        lines.append("")
    lines += ["## Neighbourhood", "", "```mermaid", "flowchart LR"]
    lines.append(f"  {mid(module.name)}[\"{module.name}\"]:::self")
    for name in sorted(module.deps):
        lines.append(f"  {mid(module.name)} --> {mid(name)}[\"{name}\"]")
    for name in sorted(module.users):
        if name not in module.deps:
            lines.append(f"  {mid(name)}[\"{name}\"] --> {mid(module.name)}")
        else:
            lines.append(f"  {mid(name)} --> {mid(module.name)}")
    lines += ["  classDef self fill:#f9d77e,stroke:#b8860b,color:#000", "```", ""]
    return "\n".join(lines)


def via_text(module, dep, modules):
    """`TypeA`, `TypeB` when the dependency is on types other than the module's namesake."""
    names = sorted(module.via.get(dep, ()))
    return "" if names == [dep] else " (" + ", ".join(f"`{n}`" for n in names) + ")"


def link_with_via(module, name, modules, title):
    if title == "Depends on":
        return f"[[{name}]]" + via_text(module, name, modules)
    return f"[[{name}]]" + via_text(modules[name], module.name, modules)


def folder_order(folder):
    order = [f for _, folders in LAYERS for f in folders]
    return order.index(folder) if folder in order else len(order)


def layer_of(folder):
    for layer, folders in LAYERS:
        if folder in folders:
            return layer
    return "Foundation"


def folders_of(modules):
    result = defaultdict(list)
    for m in modules.values():
        result[m.folder].append(m)
    return {f: sorted(ms, key=lambda m: m.name) for f, ms in sorted(result.items(), key=lambda kv: folder_order(kv[0]))}


def overview(modules):
    folders = folders_of(modules)
    edges = defaultdict(int)
    for m in modules.values():
        for d in m.deps:
            a, b = m.folder, modules[d].folder
            if a != b:
                edges[(a, b)] += 1
    lines = ["---", "tags: [diagram, generated]", "---", "", "# Dependency overview", "", GENERATED, "",
             "Folders of `src/NetSync` (≈ namespaces) and how many module-to-module references cross between them. "
             "Arrows point from the user to what it uses. Layers run top to bottom; an arrow pointing *up* is a "
             "dependency against the layering — worth a look when it appears.", "",
             "```mermaid", "flowchart TB"]
    for layer, layer_folders in LAYERS:
        for folder in layer_folders:
            if folder in folders and folder not in UTILITY_FOLDERS:
                count = len(folders[folder])
                lines.append(f"  {fid(folder)}[\"{folder}<br/>{count} module{'' if count == 1 else 's'}\"]:::{layer.lower()}")
    for (a, b), count in sorted(edges.items(), key=lambda kv: (folder_order(kv[0][0]), folder_order(kv[0][1]))):
        if b in UNDRAWN_TARGETS or a in UTILITY_FOLDERS:
            continue
        lines.append(f"  {fid(a)} -->|{count}| {fid(b)}")
    lines += [f"  classDef {layer.lower()} fill:{color},stroke:#555,color:#000" for layer, color in LAYER_COLORS.items()]
    lines += ["```", "", "Colour = layer: " + ", ".join(f"{layer}" for layer in LAYER_COLORS) + " (top to bottom). "
              "References to the utility folders and to `(root)` — `NetConfig.cs`, which also declares the "
              "`TransportType` enum nearly everything names — are left out of the drawing:", "",
              "| Folder | Used by folders (references) |", "|---|---|"]
    for util in sorted(UNDRAWN_TARGETS, key=folder_order):
        users = sorted(((a, c) for (a, b), c in edges.items() if b == util), key=lambda x: folder_order(x[0]))
        lines.append(f"| {util} | " + ", ".join(f"{a} ({c})" for a, c in users) + " |")
    lines.append("")
    upward = [(a, b, c) for (a, b), c in edges.items()
              if [l for l, fs in LAYERS if a in fs] and [l for l, fs in LAYERS if b in fs]
              and LAYER_INDEX[layer_of(a)] > LAYER_INDEX[layer_of(b)]]
    lines += ["## Dependencies against the layering", ""]
    if upward:
        lines.append("| From | To | References | Modules |")
        lines.append("|---|---|---|---|")
        for a, b, c in sorted(upward):
            pairs = sorted({f"[[{m.name}]] → [[{d}]]{via_text(m, d, modules)}" for m in folders[a] for d in m.deps if modules[d].folder == b})
            lines.append(f"| {a} | {b} | {c} | {'<br>'.join(pairs)} |")
    else:
        lines.append("None.")
    order = [f for f in folders]
    short = {f: f.replace("Transports/", "T/").replace("Pipeline/", "P/") for f in order}
    lines += ["", "## Matrix", "", "Module-to-module references from the row folder to the column folder "
              "(`T/` = Transports, `P/` = Pipeline). Above the diagonal = towards lower layers.", "",
              "| from ↓ to → | " + " | ".join(short[f] for f in order) + " |",
              "|---|" + "---|" * len(order)]
    for a in order:
        cells = []
        for b in order:
            cells.append("·" if a == b else str(edges.get((a, b), "")))
        lines.append(f"| **{short[a]}** | " + " | ".join(cells) + " |")
    lines += ["", "## Folders", "", "| Folder | Layer | Modules |", "|---|---|---|"]
    for folder, ms in folders.items():
        lines.append(f"| [[{folder_note(folder)}\\|{folder}]] | {layer_of(folder)} | {', '.join(f'[[{m.name}]]' for m in ms)} |")
    lines.append("")
    return "\n".join(lines), edges


def full_graph(modules):
    folders = folders_of(modules)
    lines = ["---", "tags: [diagram, generated]", "---", "", "# Full dependency graph", "", GENERATED, "",
             "Every module of the core and every dependency between modules, coloured by layer, users on the left, what they use on the right. "
             "References to the utility folders (`Internal`, `Diagnostics`) and to `NetConfig` (whose file also "
             "declares `TransportType`) are listed below instead of drawn — almost every module has them and they "
             "would bury everything else. The diagram is large: zoom in, or use the interactive views — Obsidian's "
             "graph view (filter `path:Code`), [[Architecture.canvas]], the per-folder maps in `Modules/`.", "",
             "```mermaid", "flowchart LR"]
    for folder, ms in folders.items():
        for m in ms:
            if folder not in UTILITY_FOLDERS:
                lines.append(f"  {mid(m.name)}[\"{m.name}<br/><small>{folder}</small>\"]:::{layer_of(folder).lower()}")
    count = 0
    for m in sorted(modules.values(), key=lambda m: (folder_order(m.folder), m.name)):
        for d in sorted(m.deps):
            if modules[d].folder in UNDRAWN_TARGETS or m.folder in UTILITY_FOLDERS:
                continue
            lines.append(f"  {mid(m.name)} --> {mid(d)}")
            count += 1
    lines += [f"  classDef {layer.lower()} fill:{color},stroke:#555,color:#000" for layer, color in LAYER_COLORS.items()]
    lines += ["```", "", f"{len(modules)} modules, {count} drawn dependencies. Colour = layer: "
              + ", ".join(LAYER_COLORS) + ".", "", "## References not drawn", ""]
    for folder in sorted(UNDRAWN_TARGETS, key=folder_order):
        for u in folders.get(folder, []):
            if u.users:
                lines.append(f"- [[{u.name}]] ← {len(u.users)} modules: " + ", ".join(f"[[{n}]]" for n in sorted(u.users)))
    lines.append("")
    return "\n".join(lines)


def hierarchy(modules):
    declared = {t["name"]: (m, t) for m in modules.values() for t in m.types if t["depth"] == 0}
    lines = ["---", "tags: [diagram, generated]", "---", "", "# Type hierarchy", "", GENERATED, "",
             "Inheritance and interface implementation among the core's own types (`..|>` implements, `--|>` extends). "
             "Transports are interchangeable through these contracts — see [[Custom transports]].", "",
             "```mermaid", "classDiagram", "  direction LR"]
    seen = set()
    for name, (m, t) in sorted(declared.items()):
        for base in t["bases"]:
            if base in declared:
                bt = declared[base][1]
                arrow = "..|>" if bt["kind"] == "interface" else "--|>"
                lines.append(f"  {name} {arrow} {base}")
                seen.update([name, base])
    for name in sorted(seen):
        t = declared[name][1]
        if t["kind"] == "interface":
            lines.append(f"  class {name}")
            lines.append(f"  <<interface>> {name}")
    lines += ["```", "", "## Who implements what", "", "| Contract | Implementations |", "|---|---|"]
    impl = defaultdict(list)
    for name, (m, t) in declared.items():
        for base in t["bases"]:
            if base in declared:
                impl[base].append(name)
    for base in sorted(impl):
        lines.append(f"| [[{declared[base][0].name}\\|{base}]] | " + ", ".join(f"[[{declared[n][0].name}\\|{n}]]" for n in sorted(impl[base])) + " |")
    lines.append("")
    return "\n".join(lines)


def module_maps(modules):
    notes = {}
    for folder, ms in folders_of(modules).items():
        names = {m.name for m in ms}
        lines = ["---", "tags: [diagram, generated]", "---", "", f"# {folder_note(folder)}", "", GENERATED, "",
                 f"Modules in `src/NetSync/{'' if folder == '(root)' else folder + '/'}`, their dependencies on each other, "
                 "and the other folders they use or are used by.", "", "```mermaid", "flowchart LR",
                 f"  subgraph {fid(folder)}[\"{folder}\"]"]
        for m in ms:
            lines.append(f"    {mid(m.name)}[\"{m.name}\"]:::{layer_of(folder).lower()}")
        lines.append("  end")
        external = {}
        edge_lines = []
        utility_uses = set()
        for m in ms:
            for d in sorted(m.deps):
                if d in names:
                    edge_lines.append(f"  {mid(m.name)} --> {mid(d)}")
                elif modules[d].folder in UTILITY_FOLDERS and folder not in UTILITY_FOLDERS:
                    utility_uses.add(d)
                else:
                    external[d] = "uses"
                    edge_lines.append(f"  {mid(m.name)} -.-> {mid(d)}")
            for u in sorted(m.users):
                if u not in names:
                    external.setdefault(u, "user")
                    edge_lines.append(f"  {mid(u)} -.-> {mid(m.name)}")
        for name in sorted(external, key=lambda n: (folder_order(modules[n].folder), n)):
            other = modules[name].folder
            lines.append(f"  {mid(name)}[\"{name}<br/><small>{other}</small>\"]:::{layer_of(other).lower()}")
        lines += edge_lines
        lines += [f"  classDef {layer.lower()} fill:{color},stroke:#555,color:#000" for layer, color in LAYER_COLORS.items()]
        lines += ["```", "", "Solid arrows stay inside the folder; dotted ones cross its boundary (outside modules are "
                  "coloured by layer)." + (" Also uses the utilities " + ", ".join(f"[[{u}]]" for u in sorted(utility_uses)) + "."
                                           if utility_uses else ""), "",
                  "| Module | Summary | Uses | Used by |", "|---|---|---|---|"]
        for m in ms:
            summary = (m.main["summary"] if m.main else "").replace("|", "\\|")
            if len(summary) > 160:
                summary = summary[:157].rsplit(" ", 1)[0] + "…"
            lines.append(f"| [[{m.name}]] | {summary} | {len(m.deps)} | {len(m.users)} |")
        lines.append("")
        notes[folder_note(folder)] = "\n".join(lines)
    return notes


def canvas(modules, edges):
    """Architecture.canvas: a group per folder with a card per module, folder-level edges between groups."""
    folders = folders_of(modules)
    nodes, canvas_edges = [], []
    card_w, card_h, gap, pad, header = 230, 50, 16, 24, 40
    group_gap_x, group_gap_y = 80, 120
    colors = {"API": "5", "Session": "4", "Transports": "6", "Infrastructure": "3", "Foundation": "2"}
    y = 0
    for layer, layer_folders in LAYERS:
        x = 0
        row_height = 0
        for folder in layer_folders:
            ms = folders.get(folder)
            if not ms:
                continue
            cols = 1 if len(ms) <= 4 else 2 if len(ms) <= 10 else 3
            rows = (len(ms) + cols - 1) // cols
            width = pad * 2 + cols * card_w + (cols - 1) * gap
            height = header + pad + rows * card_h + (rows - 1) * gap + pad
            group_id = fid(folder)
            nodes.append({"id": group_id, "type": "group", "x": x, "y": y, "width": width, "height": height,
                          "label": f"{folder} ({layer})", "color": colors[layer]})
            for i, m in enumerate(ms):
                cx = x + pad + (i % cols) * (card_w + gap)
                cy = y + header + (i // cols) * (card_h + gap)
                nodes.append({"id": mid(m.name), "type": "file", "file": f"Code/{m.folder.replace('(root)', 'Root')}/{m.name}.md",
                              "x": cx, "y": cy, "width": card_w, "height": card_h})
            x += width + group_gap_x
            row_height = max(row_height, height)
        y += row_height + group_gap_y
    for (a, b), count in edges.items():
        if b in UTILITY_FOLDERS and a not in UTILITY_FOLDERS:
            continue
        canvas_edges.append({"id": f"e_{fid(a)}_{fid(b)}", "fromNode": fid(a), "fromSide": "bottom",
                             "toNode": fid(b), "toSide": "top", "label": str(count)})
    return json.dumps({"nodes": nodes, "edges": canvas_edges}, indent=1)


def code_index(modules):
    lines = ["---", "tags: [code, generated]", "---", "", "# Code index", "", GENERATED, "",
             "Every module of `src/NetSync` by layer and folder. Each note lists its types, members, what it depends "
             "on and what uses it. Diagrams: [[Dependency overview]], [[Full dependency graph]], [[Type hierarchy]].", ""]
    folders = folders_of(modules)
    for layer, layer_folders in LAYERS:
        lines += [f"## {layer}", ""]
        for folder in layer_folders:
            if folder not in folders:
                continue
            lines += [f"### {folder} — [[{folder_note(folder)}|diagram]]", "", "| Module | Kind | Summary |", "|---|---|---|"]
            for m in folders[folder]:
                main = m.main
                summary = (main["summary"] if main else "").replace("|", "\\|")
                if len(summary) > 140:
                    summary = summary[:137].rsplit(" ", 1)[0] + "…"
                lines.append(f"| [[{m.name}]] | {kind_label(main) if main else ''} | {summary} |")
            lines.append("")
    hubs = sorted(modules.values(), key=lambda m: -len(m.users))[:10]
    lines += ["## Most used modules", "", "| Module | Used by |", "|---|---|"]
    lines += [f"| [[{m.name}]] | {len(m.users)} |" for m in hubs]
    lines.append("")
    return "\n".join(lines)


